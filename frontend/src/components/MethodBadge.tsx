import { Sparkles, Cpu, CircleDot } from "lucide-react"
import { METHOD_LABELS, type ExtractionMethod } from "@/types"
import { cn } from "@/lib/utils"

const STYLES: Record<ExtractionMethod, { icon: typeof Sparkles; classes: string }> = {
  gemini: { icon: Sparkles, classes: "bg-blue-50 text-blue-700 border-blue-200" },
  glm_bridge: { icon: Sparkles, classes: "bg-indigo-50 text-indigo-700 border-indigo-200" },
  rule_based: { icon: CircleDot, classes: "bg-amber-50 text-amber-700 border-amber-200" },
}

export function MethodBadge({ method, className }: { method: ExtractionMethod; className?: string }) {
  const style = STYLES[method] ?? STYLES.rule_based
  const Icon = method === "rule_based" ? CircleDot : method === "gemini" ? Sparkles : Cpu
  return (
    <span
      className={cn(
        "inline-flex items-center gap-1 rounded-full border px-2.5 py-0.5 text-xs font-medium",
        style.classes,
        className,
      )}
      title={`Result generated by: ${METHOD_LABELS[method]}`}
    >
      <Icon className="size-3" aria-hidden />
      {METHOD_LABELS[method]}
    </span>
  )
}
